import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const vm = await import('node:vm');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'dist', 'roverbook');
fs.mkdirSync(outDir, { recursive: true });

// assets/ 是 UMD 檔（瀏覽器直接 <script>）：在 Node 用一個「有 module.exports」的 vm 沙箱載入，
// 同 tests/browser-module-harness.mjs 的做法一致（唔會污染 globalThis）。
function loadUmd(file) {
  const src = fs.readFileSync(file, 'utf8');
  const holder = { exports: {} };
  vm.runInNewContext(src, { module: holder, exports: holder.exports, globalThis: {} });
  return holder.exports;
}
const Bridge = loadUmd(path.join(root, 'assets', 'roverbook-bridge.js'));

